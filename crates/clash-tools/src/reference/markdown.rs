fn types_index(catalog: &Catalog) -> String {
    let mut out = note();
    out.push_str("# Definition types\n\n");
    out.push_str("A data file is a JSON array of definitions, or a single one. Each is an object whose `type` names one of these types; the page of each lists its fields.\n\n");
    out.push_str("| Type | What it is |\n|------|------------|\n");
    for entry in &catalog.types {
        let mut what = cell(&first_sentence(entry.doc));
        if let Some(feature) = entry.experimental {
            let _ = write!(what, " *Experimental: `{feature}`.*");
        }
        let _ = writeln!(out, "| [`{0}`]({0}.md) | {what} |", entry.name);
    }
    out.push_str("\n## Keys every definition carries\n\n");
    out.push_str("These keys are read by the loader itself, on any definition, before its type sees it (04 §5, §6). Any other key belongs to the type.\n\n");
    for (key, doc) in DIRECTIVE_DOCS {
        let _ = writeln!(out, "- `{key}`: {}", prose(doc, "  "));
    }
    out
}

/// The anchors of the sections of one page, by key of named shape.
struct Anchors {
    by_key: BTreeMap<String, String>,
}

impl Anchors {
    fn link(&self, key: &str, name: &str) -> String {
        match self.by_key.get(key) {
            Some(anchor) => format!("[`{name}`](#{anchor})"),
            None => format!("`{name}`"),
        }
    }
}

fn slug(text: &str) -> String {
    let mut out = String::new();
    for c in text.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if (c == '.' || c == '_' || c == '-' || c == ' ') && !out.ends_with('-') {
            out.push('-');
        }
    }
    out.trim_matches('-').to_owned()
}

/// Whether a named shape gets a section of its own on a type's page.
fn has_section(shapes: &Shapes, key: &str) -> bool {
    let Some(named) = shapes.named.get(key) else {
        return false;
    };
    if is_data_layer(&named.rust) || quantity_like(named) {
        return false;
    }
    true
}

/// A field type of the world's that reads a quantity in units of its
/// own: described by what it expects, inline.
fn quantity_like(named: &clash_data::shape::Named) -> bool {
    named.rust == "clash_core::real::Real"
}

fn type_page(catalog: &Catalog, entry: &TypeEntry) -> String {
    let shapes = &entry.shapes;
    // The sections, in the order they are first reached from the root.
    let mut order: Vec<String> = Vec::new();
    let mut seen: BTreeSet<String> = BTreeSet::new();
    let mut queue: VecDeque<String> = VecDeque::new();
    let root_key = match &shapes.root {
        Shape::Named(key) => Some(key.clone()),
        _ => None,
    };
    if let Some(key) = &root_key {
        queue.push_back(key.clone());
        seen.insert(key.clone());
    }
    while let Some(key) = queue.pop_front() {
        let Some(named) = shapes.named.get(&key) else {
            continue;
        };
        if Some(&key) != root_key.as_ref() {
            if !has_section(shapes, &key) {
                continue;
            }
            order.push(key.clone());
        }
        let mut next = Vec::new();
        match &named.shape {
            NamedShape::Struct(shape) => {
                for field in &shape.fields {
                    referred(&field.shape, &mut next);
                }
            }
            NamedShape::Enum(shape) => {
                for variant in &shape.variants {
                    match &variant.form {
                        VariantForm::Newtype(inner) => referred(inner, &mut next),
                        VariantForm::Tuple(items) => {
                            for item in items {
                                referred(item, &mut next);
                            }
                        }
                        VariantForm::Struct(key) => next.push(key.clone()),
                        VariantForm::Unit | VariantForm::Unknown => {}
                    }
                }
            }
            NamedShape::Kinds(shape) => {
                for (_, inner) in &shape.accepted {
                    referred(inner, &mut next);
                }
            }
        }
        for key in next {
            if seen.insert(key.clone()) {
                queue.push_back(key);
            }
        }
    }
    let mut anchors = Anchors {
        by_key: BTreeMap::new(),
    };
    let mut used: BTreeSet<String> = ["fields".to_owned()].into_iter().collect();
    for key in &order {
        let name = shapes
            .named
            .get(key)
            .map_or(String::new(), |named| named.name.clone());
        let mut anchor = slug(&name);
        let mut n = 2;
        while !used.insert(anchor.clone()) {
            anchor = format!("{}-{n}", slug(&name));
            n += 1;
        }
        anchors.by_key.insert(key.clone(), anchor);
    }
    let known: BTreeSet<&str> = catalog.types.iter().map(|entry| entry.name).collect();
    let cx = Describe {
        shapes,
        anchors: &anchors,
        known: &known,
    };

    let mut out = note();
    let _ = writeln!(out, "# `{}`\n", entry.name);
    if !entry.doc.is_empty() {
        let _ = writeln!(out, "{}\n", prose(entry.doc, ""));
    }
    if let Some(feature) = entry.experimental {
        let _ = writeln!(
            out,
            "**Experimental** (04 §8.4): a mod that defines one names `{feature}` in the `experimental` list of its `mod.json`.\n"
        );
    }
    if !entry.builtins.is_empty() {
        let names: Vec<String> = entry
            .builtins
            .iter()
            .map(|name| format!("`engine:{name}`"))
            .collect();
        let _ = writeln!(
            out,
            "The engine supplies {}, which may be named bare (04 §4.4).\n",
            names.join(", ")
        );
    }
    let defaults = defaults(entry.defaults);
    if !defaults.is_empty() {
        let list: Vec<String> = defaults
            .iter()
            .map(|(field, value)| format!("`{field}` {value}"))
            .collect();
        let _ = writeln!(
            out,
            "Defaults that `scale` and `add` act on when a definition leaves the field out (04 §6.1): {}.\n",
            list.join(", ")
        );
    }
    out.push_str("## Fields\n\n");
    out.push_str(
        "Besides these, a definition takes the [keys every definition carries](README.md#keys-every-definition-carries).\n\n",
    );
    match root_key.as_deref().and_then(|key| shapes.named.get(key)) {
        Some(named) => match &named.shape {
            NamedShape::Struct(shape) => {
                if shape.fields.is_empty() {
                    out.push_str("It has no fields of its own.\n");
                }
                for field in &shape.fields {
                    out.push_str(&field_line(&cx, named, field, &defaults));
                }
            }
            _ => {
                let _ = writeln!(out, "Written as {}.", cx.shape(&shapes.root));
            }
        },
        None => {
            let _ = writeln!(out, "Written as {}.", cx.shape(&shapes.root));
        }
    }
    for key in &order {
        let Some(named) = shapes.named.get(key) else {
            continue;
        };
        let anchor = anchors.by_key.get(key).cloned().unwrap_or_default();
        let _ = writeln!(out, "\n<a id=\"{anchor}\"></a>\n### `{}`\n", named.name);
        if let Some(doc) = named_doc(named) {
            let _ = writeln!(out, "{}\n", prose(doc, ""));
        }
        match &named.shape {
            NamedShape::Struct(shape) => {
                if shape.fields.is_empty() {
                    out.push_str("An object with no fields.\n");
                }
                for field in &shape.fields {
                    out.push_str(&field_line(&cx, named, field, &[]));
                }
            }
            NamedShape::Enum(shape) => {
                out.push_str("One of:\n\n");
                let docs = crate::typedocs::find(&named.rust);
                for variant in &shape.variants {
                    let doc = docs.and_then(|docs| docs.item(variant.name)).unwrap_or("");
                    let form = match &variant.form {
                        VariantForm::Unit | VariantForm::Unknown => {
                            format!("`\"{}\"`", variant.name)
                        }
                        VariantForm::Newtype(inner) => {
                            format!("`{{ \"{}\": … }}` with {}", variant.name, cx.shape(inner))
                        }
                        VariantForm::Tuple(items) => {
                            let items: Vec<String> =
                                items.iter().map(|item| cx.shape(item)).collect();
                            format!(
                                "`{{ \"{}\": [ … ] }}` with {}",
                                variant.name,
                                items.join(", ")
                            )
                        }
                        VariantForm::Struct(key) => {
                            let name = shapes
                                .named
                                .get(key)
                                .map_or(variant.name.to_owned(), |n| n.name.clone());
                            format!(
                                "`{{ \"{}\": {{ … }} }}`, an object ({})",
                                variant.name,
                                anchors.link(key, &name)
                            )
                        }
                    };
                    if doc.is_empty() {
                        let _ = writeln!(out, "- {form}");
                    } else {
                        let _ = writeln!(out, "- {form}: {}", prose(doc, "  "));
                    }
                }
            }
            NamedShape::Kinds(shape) => {
                if let Some(expected) = &shape.expected {
                    let _ = writeln!(out, "Written as {expected}.\n");
                }
                let how = match shape.via {
                    Via::BySite => " (kept with where it was written, and checked when mods load)",
                    Via::ByKind | Via::Any => "",
                };
                let takes: Vec<String> = shape
                    .accepted
                    .iter()
                    .map(|(kind, inner)| kind_line(&cx, *kind, inner))
                    .collect();
                let _ = writeln!(out, "Takes{how}:\n");
                for line in takes {
                    let _ = writeln!(out, "- {line}");
                }
            }
        }
    }
    out
}

/// One accepted kind of JSON and what it is read as.
fn kind_line(cx: &Describe<'_>, kind: JsonKind, inner: &Shape) -> String {
    let article = if matches!(kind, JsonKind::Integer | JsonKind::Object) {
        "an"
    } else {
        "a"
    };
    let plain = matches!(
        inner,
        Shape::Any
            | Shape::Unknown
            | Shape::String
            | Shape::Real
            | Shape::Bool
            | Shape::Unit
            | Shape::Int { .. }
            | Shape::Char
    );
    if plain {
        return format!("{article} {}", kind.name());
    }
    format!("{article} {}: {}", kind.name(), cx.shape(inner))
}

/// The defaults of `Def::DEFAULTS`, as field and value.
fn defaults(text: &str) -> Vec<(String, String)> {
    if text.trim().is_empty() {
        return Vec::new();
    }
    let mut sources = clash_data::SourceMap::new();
    let file = sources.add("defaults.json", text);
    let (tree, _) =
        clash_data::parse_json(file, sources.text(file), &clash_data::Limits::default());
    tree.as_ref()
        .and_then(|tree| tree.as_object())
        .map(|members| {
            members
                .iter()
                .map(|member| (member.key.clone(), member.value.to_json()))
                .collect()
        })
        .unwrap_or_default()
}

fn field_line(
    cx: &Describe<'_>,
    named: &clash_data::shape::Named,
    field: &clash_data::shape::FieldShape,
    defaults: &[(String, String)],
) -> String {
    let mut what = cx.shape(&field.shape);
    if field.required {
        what.push_str("; **required**");
    } else if let Some((_, value)) = defaults.iter().find(|(name, _)| name == field.name) {
        let _ = write!(what, "; default `{value}`");
    } else {
        what.push_str("; optional");
    }
    match field_doc(named, field.name) {
        Some(doc) => format!("- `{}` ({what}): {}\n", field.name, prose(doc, "  ")),
        None => format!("- `{}` ({what})\n", field.name),
    }
}

/// What describing a shape needs.
struct Describe<'a> {
    shapes: &'a Shapes,
    anchors: &'a Anchors,
    known: &'a BTreeSet<&'a str>,
}

impl Describe<'_> {
    fn def_link(&self, name: &str) -> String {
        if self.known.contains(name) {
            format!("[`{name}`]({name}.md)")
        } else {
            format!("`{name}`")
        }
    }

    fn shape(&self, shape: &Shape) -> String {
        match shape {
            Shape::Unknown => "a value".to_owned(),
            Shape::Bool => "`true` or `false`".to_owned(),
            Shape::Int { signed: false } => "whole number, 0 or more".to_owned(),
            Shape::Int { signed: true } => "whole number".to_owned(),
            Shape::Real => "number".to_owned(),
            Shape::Char => "one character".to_owned(),
            Shape::String => "string".to_owned(),
            Shape::Quantity(dim) => quantity(*dim, "../"),
            Shape::Duration => quantity(Dim::TIME, "../"),
            Shape::Ref(ty) => format!("id of a {}", self.def_link(ty)),
            Shape::Inline(ty) => format!(
                "{}, by id or [written in place](../values.md#inline-definitions)",
                self.def_link(ty)
            ),
            Shape::Tag => "[tag](../values.md#tags)".to_owned(),
            Shape::List(inner) => match inner.as_ref() {
                Shape::Unknown => "list".to_owned(),
                inner => format!("list of {}", self.shape(inner)),
            },
            Shape::Tuple(items) => {
                let items: Vec<String> = items.iter().map(|item| self.shape(item)).collect();
                format!("list of {}: {}", items.len(), items.join(", "))
            }
            Shape::Map(key, value) => {
                let key = match key.as_ref() {
                    Shape::String => "name".to_owned(),
                    other => self.shape(other),
                };
                match value.as_ref() {
                    Shape::Unknown => "object".to_owned(),
                    value => {
                        let value = self.shape(value);
                        if value.contains(" → ") {
                            format!("object, {key} → ({value})")
                        } else {
                            format!("object, {key} → {value}")
                        }
                    }
                }
            }
            Shape::Optional(inner) => format!("{}, or `null`", self.shape(inner)),
            Shape::Gated(feature, inner) => {
                format!("{}; experimental feature `{feature}`", self.shape(inner))
            }
            Shape::Any => "any JSON value".to_owned(),
            Shape::Unit => "`null`".to_owned(),
            Shape::Named(key) => self.named(key),
        }
    }

    fn named(&self, key: &str) -> String {
        let Some(named) = self.shapes.named.get(key) else {
            return "a value".to_owned();
        };
        if let Some((anchor, name)) = data_layer(&named.rust) {
            let name = match (name, expr_type(&named.rust)) {
                ("expression", Some(ty)) => format!("expression of {ty}"),
                (name, _) => name.to_owned(),
            };
            return format!("[{name}](../values.md#{anchor})");
        }
        match &named.shape {
            NamedShape::Kinds(shape) if quantity_like(named) => shape
                .expected
                .clone()
                .unwrap_or_else(|| "a number or a string with a unit".to_owned()),
            NamedShape::Enum(shape)
                if shape.variants.len() <= 6
                    && shape
                        .variants
                        .iter()
                        .all(|variant| matches!(variant.form, VariantForm::Unit)) =>
            {
                let values: Vec<String> = shape
                    .variants
                    .iter()
                    .map(|variant| format!("`\"{}\"`", variant.name))
                    .collect();
                format!(
                    "one of {} ({})",
                    values.join(", "),
                    self.anchors.link(key, &named.name)
                )
            }
            NamedShape::Struct(_) => format!("object {}", self.anchors.link(key, &named.name)),
            _ => self.anchors.link(key, &named.name),
        }
    }
}

/// A quantity's name and its SI unit, linked to the units page.
fn quantity(dim: Dim, up: &str) -> String {
    let name = dim.name();
    let name = name
        .strip_prefix("a ")
        .or_else(|| name.strip_prefix("an "))
        .unwrap_or(name);
    let unit = dim.si_unit();
    if unit.is_empty() {
        return format!("[{name}]({up}units.md)");
    }
    format!("[{name}]({up}units.md#{}) in `{unit}`", slug(name))
}

