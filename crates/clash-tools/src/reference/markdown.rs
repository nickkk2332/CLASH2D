/// The command that writes the committed reference.
pub const COMMAND: &str = "cargo run -p clash-tools -- docs --out docs/reference";

/// The note at the top of every page.
fn note() -> String {
    format!(
        "<!-- Generated by `{COMMAND}` from the engine's registries. Do not edit: change the documentation in the engine and run the command again. -->\n"
    )
}

/// Every page, by its path under the output directory.
pub fn pages(catalog: &Catalog) -> BTreeMap<String, String> {
    let mut pages = BTreeMap::new();
    pages.insert("README.md".to_owned(), index(catalog));
    pages.insert("types/README.md".to_owned(), types_index(catalog));
    for entry in &catalog.types {
        pages.insert(
            format!("types/{}.md", entry.name),
            type_page(catalog, entry),
        );
    }
    pages.insert("values.md".to_owned(), values_page());
    pages.insert("units.md".to_owned(), units_page());
    pages.insert(
        "properties.md".to_owned(),
        properties_page(&catalog.registry),
    );
    pages.insert("functions.md".to_owned(), functions_page(&catalog.registry));
    pages.insert(
        "events.md".to_owned(),
        events_page(&catalog.registry, false),
    );
    pages.insert("hooks.md".to_owned(), events_page(&catalog.registry, true));
    pages.insert("verbs.md".to_owned(), verbs_page(&catalog.registry));
    pages.insert("effects.md".to_owned(), effects_page(catalog));
    pages.insert("queries.md".to_owned(), queries_page(&catalog.registry));
    pages.insert("settings.md".to_owned(), settings_page(catalog));
    pages.insert("reasons.md".to_owned(), reasons_page(catalog));
    pages.insert("diagnostics.md".to_owned(), diagnostics_page(catalog));
    pages
}

/// A text made into one Markdown paragraph run: Rust links cleaned,
/// paragraphs kept, and indented to continue a list item.
fn prose(text: &str, indent: &str) -> String {
    clean(text.trim()).replace("\n\n", &format!("\n\n{indent}"))
}

/// A text made fit for one cell of a table.
fn cell(text: &str) -> String {
    clean(text.trim())
        .replace("\n\n", " ")
        .replace('\n', " ")
        .replace('|', "\\|")
}

