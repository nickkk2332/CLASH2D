fn units_page() -> String {
    let mut out = note();
    out.push_str("# Units\n\n");
    out.push_str("A quantity is written as a number in the field's SI unit, or as a string of a number and one of these units (04 §7.1). Units are case-sensitive.\n\n");
    let mut dims: Vec<Dim> = Vec::new();
    for unit in UNITS {
        if !dims.contains(&unit.dim) {
            dims.push(unit.dim);
        }
    }
    out.push_str("| Measures | SI unit | Units |\n|----------|---------|-------|\n");
    for dim in &dims {
        let name = dim.name();
        let name = name
            .strip_prefix("a ")
            .or_else(|| name.strip_prefix("an "))
            .unwrap_or(name);
        let units: Vec<String> = UNITS
            .iter()
            .filter(|unit| unit.dim == *dim)
            .map(|unit| format!("`{}`", unit.symbol))
            .collect();
        let _ = writeln!(
            out,
            "| <a id=\"{}\"></a>{name} | `{}` | {} |",
            slug(name),
            dim.si_unit(),
            units.join(" ")
        );
    }
    out.push_str("\n## Rates\n\n");
    let per: Vec<String> = RATE_UNITS
        .iter()
        .map(|(unit, _)| format!("`/{unit}`"))
        .collect();
    let _ = writeln!(
        out,
        "A rate is a unit followed by one of {}: `\"0.012 kg/s\"`, `\"2 C/s\"`. A plain rate has no unit before the slash: `\"0.15 /h\"`. A speed is a length per time and a power an energy per time, so `\"18 km/h\"` and `\"5 J/s\"` are read too. A rate of temperature is a difference: `\"2 C/s\"` is two kelvin a second.\n",
        per.join(", ")
    );
    out.push_str("| Measures | SI unit | Also written |\n|----------|---------|--------------|\n");
    for base in [
        Base::Count,
        Base::Time,
        Base::Length,
        Base::Volume,
        Base::Mass,
        Base::Energy,
        Base::Force,
        Base::Pressure,
        Base::Temperature,
    ] {
        let dim = Dim::of(base).rate();
        let name = dim.name();
        let name = name
            .strip_prefix("a ")
            .or_else(|| name.strip_prefix("an "))
            .unwrap_or(name);
        let _ = writeln!(
            out,
            "| <a id=\"{}\"></a>{name} | `{}` | {} |",
            slug(name),
            dim.si_unit(),
            dim.accepted_units()
                .split(' ')
                .filter(|unit| !unit.is_empty() && !unit.starts_with('(') && !unit.ends_with(')'))
                .map(|unit| format!("`{unit}`"))
                .collect::<Vec<_>>()
                .join(" ")
        );
    }
    out.push_str("\nIn an expression only the units that are a scale may follow a number, without a slash: `300ms`, `70kPa`. `C` is an offset and is not one of them (05 §4.7).\n");
    out
}

fn param_lines(registry: &ExprRegistry, params: &[ParamSpec], out: &mut String) {
    for param in params {
        let ty = registry.type_name(&param.ty);
        let optional = if param.optional { ", optional" } else { "" };
        if param.doc.trim().is_empty() {
            let _ = writeln!(out, "- `{}` ({ty}{optional})", param.name);
        } else {
            let _ = writeln!(
                out,
                "- `{}` ({ty}{optional}): {}",
                param.name,
                prose(&param.doc, "  ")
            );
        }
    }
}

fn properties_page(registry: &ExprRegistry) -> String {
    let mut out = note();
    out.push_str("# Kinds of subject and their properties\n\n");
    out.push_str("A subject is a reference to something in the simulation, of a known kind; an expression reads its properties: `self.loc`, `here.block.material` (05 §5). A property marked *safe for belief* may be read of anything in a mind context; any other, only of the character's own subject (05 §7.3). One marked *settable* may be assigned with `set`.\n\n");
    let mut kinds: Vec<_> = registry.kinds().collect();
    kinds.sort_by(|a, b| a.spec.name.cmp(&b.spec.name));
    out.push_str(
        "| Kind | What it refers to | Properties |\n|------|-------------------|-----------:|\n",
    );
    for kind in &kinds {
        let count = registry.properties_of(kind.id).count();
        let _ = writeln!(
            out,
            "| [`{0}`](#{1}) | {2} | {count} |",
            kind.spec.name,
            slug(&kind.spec.name),
            cell(&first_sentence(&kind.spec.doc))
        );
    }
    for kind in &kinds {
        let _ = writeln!(
            out,
            "\n<a id=\"{}\"></a>\n## `{}`\n",
            slug(&kind.spec.name),
            kind.spec.name
        );
        if !kind.spec.doc.is_empty() {
            let _ = writeln!(out, "{}\n", prose(&kind.spec.doc, ""));
        }
        let mut properties: Vec<_> = registry.properties_of(kind.id).collect();
        properties.sort_by(|a, b| a.spec.name.cmp(&b.spec.name));
        if properties.is_empty() {
            out.push_str("No properties.\n");
        }
        for property in properties {
            let signature = registry.property_signature(property);
            let mut marks = Vec::new();
            if property.spec.belief_safe {
                marks.push("safe for belief");
            }
            if property.spec.settable {
                marks.push("settable");
            }
            if property.spec.yields_own {
                marks.push("same owner");
            }
            let marks = if marks.is_empty() {
                String::new()
            } else {
                format!(" · {}", marks.join(" · "))
            };
            let _ = writeln!(
                out,
                "- `{signature}`{marks}: {}",
                prose(&property.spec.doc, "  ")
            );
            if !property.spec.changed_by.is_empty() {
                let events: Vec<String> = property
                    .spec
                    .changed_by
                    .iter()
                    .map(|event| format!("`{event}`"))
                    .collect();
                let _ = writeln!(out, "  Changed by {}.", events.join(", "));
            }
            let mut params = String::new();
            param_lines(registry, &property.spec.params, &mut params);
            for line in params.lines() {
                let _ = writeln!(out, "  {line}");
            }
        }
    }
    out
}

fn functions_page(registry: &ExprRegistry) -> String {
    let mut out = note();
    out.push_str("# Functions\n\n");
    out.push_str("Functions are called from expressions (05 §4.7, §12). A random one draws from the rule stream and is refused in a pure context; one that is not *safe for belief* is refused in a mind context, where a character decides by what it has perceived (05 §7.3). Functions mods define are listed in their own files, not here.\n\n");
    let mut groups: BTreeMap<String, Vec<_>> = BTreeMap::new();
    for function in registry.functions() {
        let group = if function.spec.group.is_empty() {
            "Other".to_owned()
        } else {
            function.spec.group.clone()
        };
        groups.entry(group).or_default().push(function);
    }
    for (group, mut functions) in groups {
        functions.sort_by(|a, b| a.spec.name.cmp(&b.spec.name));
        let _ = writeln!(out, "## {group}\n");
        for function in functions {
            let mut marks = Vec::new();
            marks.push(if function.spec.belief_safe {
                "safe for belief"
            } else {
                "not in a mind context"
            });
            if function.spec.random {
                marks.push("random");
            }
            if function.spec.changed_by.is_some() {
                marks.push("reactive");
            }
            let _ = writeln!(
                out,
                "<a id=\"{}\"></a>\n### `{}`\n\n`{}` · {}\n",
                slug(&function.spec.name),
                function.spec.name,
                registry.signature(function),
                marks.join(" · ")
            );
            if !function.spec.doc.is_empty() {
                let _ = writeln!(out, "{}\n", prose(&function.spec.doc, ""));
            }
            let mut params = String::new();
            param_lines(registry, &function.spec.params, &mut params);
            if !params.is_empty() {
                let _ = writeln!(out, "{params}");
            }
            if let Some(events) = &function.spec.changed_by
                && !events.is_empty()
            {
                let events: Vec<String> = events.iter().map(|event| format!("`{event}`")).collect();
                let _ = writeln!(out, "Its result changes on {}.\n", events.join(", "));
            }
        }
    }
    out
}

fn events_page(registry: &ExprRegistry, hooks: bool) -> String {
    let mut out = note();
    if hooks {
        out.push_str("# Hooks\n\n");
        out.push_str("A hook is raised before the operation it names, and delivered at once: a handler may change the fields listed as changeable, with `modify` or `set`, or stop the operation with `cancel_event` (05 §8.2). Every event also binds `actor` and `instigator` from its cause where the cause names them.\n\n");
    } else {
        out.push_str("# Events\n\n");
        out.push_str("A notification says that something happened. A rule listens with `on`, binds the event's subjects by name, reads its fields as `event.field` and may `filter` on them (05 §8, §9). Every event also binds `actor` and `instigator` from its cause where the cause names them. Events mods define are listed in their own files. [Hooks](hooks.md) are on a page of their own.\n\n");
    }
    let mut events: Vec<_> = registry
        .events()
        .filter(|event| event.spec.hook == hooks)
        .collect();
    events.sort_by(|a, b| a.spec.name.cmp(&b.spec.name));
    for event in events {
        let _ = writeln!(
            out,
            "<a id=\"{}\"></a>\n## `{}`\n",
            slug(&event.spec.name),
            event.spec.name
        );
        if !event.spec.doc.is_empty() {
            let _ = writeln!(out, "{}\n", prose(&event.spec.doc, ""));
        }
        let subjects: Vec<String> = event
            .spec
            .subjects
            .iter()
            .filter(|(name, _)| name != "actor" && name != "instigator")
            .map(|(name, kind)| {
                let kind = registry
                    .kind(*kind)
                    .map_or("?".to_owned(), |kind| kind.spec.name.clone());
                format!("`{name}` ({kind})")
            })
            .collect();
        if subjects.is_empty() {
            out.push_str("Subjects: none of its own.\n\n");
        } else {
            let _ = writeln!(
                out,
                "Subjects, in delivery order: {}.\n",
                subjects.join(", ")
            );
        }
        if event.spec.fields.is_empty() {
            out.push_str("No fields.\n\n");
        } else {
            out.push_str("Fields:\n\n");
            let mut params = String::new();
            param_lines(registry, &event.spec.fields, &mut params);
            let _ = writeln!(out, "{params}");
        }
        if hooks {
            if event.spec.mutable.is_empty() {
                out.push_str("A handler may change no field; it may cancel.\n\n");
            } else {
                let fields: Vec<String> = event
                    .spec
                    .mutable
                    .iter()
                    .map(|field| format!("`{field}`"))
                    .collect();
                let _ = writeln!(
                    out,
                    "A handler may change {}, or cancel.\n",
                    fields.join(", ")
                );
            }
        }
    }
    out
}

fn verbs_page(registry: &ExprRegistry) -> String {
    let mut out = note();
    out.push_str("# Verbs\n\n");
    out.push_str("A verb is what an effect calls: `{ \"damage\": { \"at\": \"here\", … } }` (05 §10.1, §10.7). Its arguments are given by name, each an expression of the declared type; one marked *direct* may be given alone. A verb that declines gives a [reason](reasons.md) and the rule carries on. The console offers every verb as a command (14 §3.3). Rules with parameters that mods define are verbs too, under their qualified ids. The effects of the rule system itself are on the [effects](effects.md) page.\n\n");
    let mut verbs: Vec<_> = registry.verbs().collect();
    verbs.sort_by(|a, b| a.spec.name.cmp(&b.spec.name));
    for verb in verbs {
        let _ = writeln!(
            out,
            "<a id=\"{}\"></a>\n## `{}`\n",
            slug(&verb.spec.name),
            verb.spec.name
        );
        if !verb.spec.doc.is_empty() {
            let _ = writeln!(out, "{}\n", prose(&verb.spec.doc, ""));
        }
        if verb.spec.args.is_empty() {
            out.push_str("No arguments: `{ \"");
            out.push_str(&verb.spec.name);
            out.push_str("\": {} }`.\n\n");
            continue;
        }
        if let Some(direct) = &verb.spec.direct {
            let _ = writeln!(out, "`{direct}` may be given directly.\n");
        }
        let mut params = String::new();
        param_lines(registry, &verb.spec.args, &mut params);
        let _ = writeln!(out, "{params}");
    }
    out
}

